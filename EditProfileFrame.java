    private void btnSaveChangesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveChangesActionPerformed
        String newUsername = txtUsername.getText().trim();
        String newFullName = txtFullName.getText().trim();
        String newPassword = new String(txtPassword.getPassword()).trim();
        String newBio = null;

        if (currentUser instanceof PremiumUser) {
            newBio = txtBio.getText().trim();
            if (newBio.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Bio cannot be empty for Premium users.");
                return;
            }
        }

        boolean updated = userDAO.updateUserProfile(currentUser, newUsername, newFullName, newPassword, newBio);

        if (updated) {
            JOptionPane.showMessageDialog(this, "Profile updated successfully.");
        } else {
            JOptionPane.showMessageDialog(this, "Profile could not be updated. Username may already exist or fields may be empty.");
        }
    }//GEN-LAST:event_btnSaveChangesActionPerformed

