    private void loadUsers(String searchText) {
        tableModel.setRowCount(0);
        displayedUsers.clear();

        for (User user : userDAO.searchUsers(searchText, currentUser)) {
            displayedUsers.add(user);

            tableModel.addRow(new Object[]{
                user.getId(),
                user.getUsername(),
                user.getFullName()
            });
        }
    }

