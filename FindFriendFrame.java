    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String searchText = txtSearch.getText().trim();

        if (searchText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a username or full name to search.");
            tableModel.setRowCount(0);
            displayedUsers.clear();
            return;
        }

        loadUsers(searchText);
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnSendRequestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSendRequestActionPerformed
        int selectedRow = tblUsers.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a user.");
            return;
        }

        User selectedUser = displayedUsers.get(selectedRow);

        boolean sent = friendRequestDAO.sendFriendRequest(currentUser, selectedUser);

        if (sent) {
            JOptionPane.showMessageDialog(this, "Friend request sent.");
        } else {
            JOptionPane.showMessageDialog(this, "Friend request could not be sent.");
        }
    }//GEN-LAST:event_btnSendRequestActionPerformed

