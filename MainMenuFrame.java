    private void loadUserInfo() {
        String password = currentUser.getPassword();
        String masked = "*".repeat(password.length());

        lblUsername.setText("User: " + currentUser.getUsername()
                + " | Password: " + masked);
    }

    private void updateSummaryFields() {
        int pendingCount = friendRequestDAO.getPendingRequestCount(currentUser);
        int friendCount = friendshipDAO.getFriendCount(currentUser);
        int closeFriendCount = friendshipDAO.getCloseFriendCount(currentUser);

        lblPendingRequestsCount.setText(String.valueOf(pendingCount));
        lblFriendsCount.setText(String.valueOf(friendCount));
        lblCloseFriendsCount.setText(String.valueOf(closeFriendCount));
        lblCloseFriendRatio.setText(calculateCloseFriendRatio(friendCount, closeFriendCount));
    }

    private String calculateCloseFriendRatio(int friendCount, int closeFriendCount) {
        if (friendCount == 0) {
            return "Close Friend Ratio: 0%";
        }

        double ratio = ((double) closeFriendCount / friendCount) * 100;
        return String.format("Close Friend Ratio: %.1f%%", ratio);
    }

    @Override
    public void setVisible(boolean visible) { //numbers refresh
        if (visible && currentUser != null && friendRequestDAO != null && friendshipDAO != null) {
            updateSummaryFields();
        }
        super.setVisible(visible);
    }

