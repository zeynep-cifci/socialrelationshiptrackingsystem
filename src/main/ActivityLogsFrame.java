    public ActivityLogsFrame(SocialMediaSystem system, User currentUser) {
        initComponents();
        this.system = system;
        this.currentUser = currentUser;
        this.activityLogDAO = new ActivityLogDAO();

        tableModel = new DefaultTableModel(
                new Object[]{"Log ID", "Username", "Action", "Description", "Date"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        tblLogs.setModel(tableModel);

        loadLogs();
        setLocationRelativeTo(null);
    }

    private void loadLogs() {
        tableModel.setRowCount(0);

        try {
            ResultSet rs = activityLogDAO.getAllLogs();

            while (rs != null && rs.next()) {
                tableModel.addRow(new Object[]{
                    rs.getInt("log_id"),
                    rs.getString("username"),
                    rs.getString("action_type"),
                    rs.getString("description"),
                    rs.getTimestamp("created_at")
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Could not load activity logs.");
            System.out.println("Load logs error: " + e.getMessage());
        }
    }

