    public static void main(String args[]) {
        java.awt.EventQueue.invokeLater(new Runnable() {
            public void run() {
                SocialMediaSystem system = new SocialMediaSystem();

                User currentUser = new User("ayse", "123", "Ayse Demir");
                User viewedUser = new User("ali123", "456", "Ali Veli");
                User extraUser = new User("mehmet", "789", "Mehmet Kaya");

                system.addUser(currentUser);
                system.addUser(viewedUser);
                system.addUser(extraUser);

                system.sendFriendRequest(extraUser, viewedUser);

                if (!system.getRequests().isEmpty()) {
                    system.acceptFriendRequest(system.getRequests().get(0));
                }

                new UserProfileFrame(system, currentUser, viewedUser).setVisible(true);
            }
        });
    }

