    //polymorphism - If viewedUser is a PremiumUser, it shows the premium summary.
    private void loadProfile() {
        lblUsername.setText(viewedUser.getUsername());
        lblFullName.setText("| " + viewedUser.getFullName());
        lblFriendCount.setText(String.valueOf(friendshipDAO.getFriendCount(viewedUser)));
        lblCloseFriendsCount.setText(String.valueOf(friendshipDAO.getCloseFriendCount(viewedUser)));

        lblProfileSummary.setText(viewedUser.getProfileSummary());
    }

