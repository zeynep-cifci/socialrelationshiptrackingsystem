    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int selectedRow = tblFriends.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a friend.");
            return;
        }

        User selectedFriend = displayedFriends.get(selectedRow);

        String selectedStatus = cmbFriendStatus.getSelectedItem().toString();
        boolean isCloseFriend = selectedStatus.equals("Close Friend");

        String note = txtNote.getText().trim();

        boolean success = friendshipDAO.updateFriendshipDetails(currentUser, selectedFriend, isCloseFriend, note);
        if (success) {
            JOptionPane.showMessageDialog(this, "Friend status updated.");
            loadFriends();
        } else {
            JOptionPane.showMessageDialog(this, "Operation failed.");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnRemoveFriendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveFriendActionPerformed
        int selectedRow = tblFriends.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a friend.");
            return;
        }

        User selectedFriend = displayedFriends.get(selectedRow);

        boolean removed = friendshipDAO.removeFriend(currentUser, selectedFriend);
        if (removed) {
            JOptionPane.showMessageDialog(this, "Friend removed.");
            loadFriends();
            txtNote.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Could not remove friend.");
        }
    }//GEN-LAST:event_btnRemoveFriendActionPerformed

