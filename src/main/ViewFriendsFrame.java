    private void tblFriendsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblFriendsMouseClicked
        int selectedRow = tblFriends.getSelectedRow();

        if (selectedRow == -1) {
            return;
        }

        User selectedFriend = displayedFriends.get(selectedRow);

        if (friendshipDAO.isCloseFriend(currentUser, selectedFriend)) {
            cmbFriendStatus.setSelectedItem("Close Friend");
        } else {
            cmbFriendStatus.setSelectedItem("Normal Friend");
        }

        String note = friendshipDAO.getFriendshipNote(currentUser, selectedFriend);
        txtNote.setText(note);
    }//GEN-LAST:event_tblFriendsMouseClicked

