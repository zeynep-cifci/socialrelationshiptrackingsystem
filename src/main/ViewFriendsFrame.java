    private void loadFriends() {
        tableModel.setRowCount(0);
        displayedFriends.clear();

        for (User friend : friendshipDAO.getFriendsOfUser(currentUser)) {
            displayedFriends.add(friend);

            String status;
            if (friendshipDAO.isCloseFriend(currentUser, friend)) {
                status = "Close Friend";
            } else {
                status = "Normal Friend";
            }

            String note = friendshipDAO.getFriendshipNote(currentUser, friend);

            tableModel.addRow(new Object[]{
                friend.getId(),
                friend.getUsername(),
                friend.getFullName(),
                status,
                note
            });
        }
    }

