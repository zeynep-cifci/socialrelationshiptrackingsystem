    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccountActionPerformed
        String fullName = txtFullName.getText().trim();
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (fullName.isEmpty() || username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields.");
            return;
        }

        User newUser;

        if (chkPremium.isSelected()) {
            String bio = txtBio.getText().trim();

            if (bio.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter a bio for your Premium account.");
                return;
            }

            newUser = new PremiumUser(username, password, fullName, bio);
        } else {
            newUser = new User(username, password, fullName);
        }

        boolean added = userDAO.addUser(newUser);

        if (added) {
            LogManager.log(newUser, "REGISTER", newUser.getUsername() + " registered.");

            JOptionPane.showMessageDialog(this, "Account created successfully. Your database ID is: " + newUser.getId());

            LoginFrame loginFrame = new LoginFrame(system);
            loginFrame.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Username already exists or database error occurred.");
        }
    }//GEN-LAST:event_btnCreateAccountActionPerformed

