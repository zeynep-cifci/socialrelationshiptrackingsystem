    public OldFriendsFrame(SocialMediaSystem system, User currentUser) {
        initComponents();
        this.system = system;
        this.oldFriendDAO = new OldFriendDAO();
        this.currentUser = currentUser;
        setLocationRelativeTo(null);

        displayedOldFriends = new ArrayList<>();

        tableModel = new DefaultTableModel(
                new Object[]{"ID", "Username", "Full Name"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        tblOldFriends.setModel(tableModel);

        loadOldFriends();
    }

    private void loadOldFriends() {
        tableModel.setRowCount(0);
        displayedOldFriends.clear();

        for (User oldFriend : oldFriendDAO.getOldFriendsOfUser(currentUser)) {
            displayedOldFriends.add(oldFriend);

            tableModel.addRow(new Object[]{
                oldFriend.getId(),
                oldFriend.getUsername(),
                oldFriend.getFullName()
            });
        }
    }

