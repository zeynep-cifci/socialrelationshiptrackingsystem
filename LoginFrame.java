    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText().trim();   //login comes from mysql
        String password = new String(txtPassword.getPassword()).trim();

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter username and password.");
            return;
        }

        User user = userDAO.login(username, password);

        if (user != null) {
            LogManager.log(user, "LOGIN", user.getUsername() + " logged in.");

            JOptionPane.showMessageDialog(this, "Login successful. User ID: " + user.getId());

            new MainMenuFrame(system, user).setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Login failed. Check username or password.");
        }
    }//GEN-LAST:event_btnLoginActionPerformed

