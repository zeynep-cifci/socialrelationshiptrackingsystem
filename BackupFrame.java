    private void btnCreateBackupActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateBackupActionPerformed
        boolean success = backupManager.createBackup(currentUser);

        if (success) {
            JOptionPane.showMessageDialog(this, "Binary backup created successfully.");
        } else {
            JOptionPane.showMessageDialog(this, "Backup could not be created.");
        }    }//GEN-LAST:event_btnCreateBackupActionPerformed

    private void btnReadBackupActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReadBackupActionPerformed
        ArrayList<String> lines = backupManager.readBackup();

        if (lines.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No backup data found.");
            return;
        }

        txtBackupContent.setText("");

        for (String line : lines) {
            txtBackupContent.append(line + "\n");
        }    }//GEN-LAST:event_btnReadBackupActionPerformed

