    private void btnAcceptAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAcceptAllActionPerformed
        ArrayList<FriendRequest> pending = new ArrayList<>(displayedRequests);
        if (pending.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No pending requests.");
            return;
        }
        for (FriendRequest req : pending) {
            friendRequestDAO.acceptRequest(req);
        }
        loadRequests();
        JOptionPane.showMessageDialog(this, "All requests accepted.");
    }//GEN-LAST:event_btnAcceptAllActionPerformed

    private void btnRejectAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRejectAllActionPerformed
        ArrayList<FriendRequest> pending = new ArrayList<>(displayedRequests);
        if (pending.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No pending requests.");
            return;
        }
        for (FriendRequest req : pending) {
            friendRequestDAO.rejectRequest(req);
        }
        loadRequests();
        JOptionPane.showMessageDialog(this, "All requests rejected.");
    }//GEN-LAST:event_btnRejectAllActionPerformed

