    private void btnAcceptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAcceptActionPerformed
        int selectedIndex = lstRequests.getSelectedIndex();

        if (selectedIndex == -1) {
            JOptionPane.showMessageDialog(this, "Please select a request.");
            return;
        }

        FriendRequest selectedRequest = displayedRequests.get(selectedIndex);

        boolean accepted = friendRequestDAO.acceptRequest(selectedRequest);

        if (accepted) {
            JOptionPane.showMessageDialog(this, "Request accepted.");
            loadRequests();
        } else {
            JOptionPane.showMessageDialog(this, "Request could not be accepted.");
        }
    }//GEN-LAST:event_btnAcceptActionPerformed

    private void btnRejectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRejectActionPerformed
        int selectedIndex = lstRequests.getSelectedIndex();

        if (selectedIndex == -1) {
            JOptionPane.showMessageDialog(this, "Please select a request.");
            return;
        }

        FriendRequest selectedRequest = displayedRequests.get(selectedIndex);

        boolean rejected = friendRequestDAO.rejectRequest(selectedRequest);

        if (rejected) {
            JOptionPane.showMessageDialog(this, "Request rejected.");
            loadRequests();
        } else {
            JOptionPane.showMessageDialog(this, "Request could not be rejected.");
        }
    }//GEN-LAST:event_btnRejectActionPerformed

