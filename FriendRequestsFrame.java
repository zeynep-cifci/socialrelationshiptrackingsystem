    private void loadRequests() {
        requestListModel.clear();
        displayedRequests.clear();

        for (FriendRequest request : friendRequestDAO.getPendingRequestsForUser(currentUser)) {
            displayedRequests.add(request);
            requestListModel.addElement(request.toString());
        }
    }

